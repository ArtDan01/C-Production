static int detectVtxByFreq(uint16_t freq)
{   
    if (freq >= 7060 && freq <= 7210){
        for(size_t i = 0; i < VTX_TABLE_MAX_CHANNELS; i++){
            if (freq == vtxTableFrequency[vtxBandRanges[VTX7G5].minBand - 1][i]) return vtxRanges[VTX7G5].type;
        }
        return vtxRanges[VTX6G1].type;
    }
    for (size_t i = 0; i < sizeof(vtxRanges) / sizeof(vtxRanges[0]); i++) {
        if (freq > vtxRanges[i].min && freq < vtxRanges[i].max) {
            detectedVtx = true;
            return vtxRanges[i].type;
        }
    }
    return UNKNOWN;
}

const char* getVtxString(int8_t vtx_type)
{
    switch (vtx_type)
    {
        case 0: return "VTX:1.2G";
        case 1: return "VTX:1.8G";
        case 2: return "VTX:3.5G";
        case 3: return "VTX:4.9G";
        case 4: return "VTX:6.1G";
        case 5: return "VTX:7.5G";
        case 6: return "UNKNOWN";
        default: return "";
    }
}


